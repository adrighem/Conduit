#!/usr/bin/env python3
"""Regenerate src/emoji/slack_names.tsv from iamcal's emoji-datasource.

Slack names its standard emoji after this dataset, so the table lets Conduit
resolve every name Slack can send. Usage:

    scripts/update-slack-emoji-names.py [VERSION]
"""

import json
import sys
import urllib.request
from pathlib import Path

DEFAULT_VERSION = "16.0.0"
URL = "https://cdn.jsdelivr.net/npm/emoji-datasource@{version}/emoji.json"
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "emoji" / "slack_names.tsv"


def unified_to_text(unified: str) -> str:
    return "".join(chr(int(code, 16)) for code in unified.split("-"))


def build_lines(entries: list[dict[str, object]]) -> list[str]:
    seen: set[str] = set()
    lines: list[str] = []
    for entry in sorted(entries, key=lambda item: int(str(item["sort_order"]))):
        names = [str(name) for name in entry["short_names"]]  # type: ignore[attr-defined]
        duplicates = seen.intersection(names)
        if duplicates:
            raise ValueError(f"duplicate Slack emoji names: {sorted(duplicates)}")
        seen.update(names)
        lines.append(f"{unified_to_text(str(entry['unified']))}\t{','.join(names)}")
    return lines


def main() -> None:
    version = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_VERSION
    with urllib.request.urlopen(URL.format(version=version)) as response:
        entries = json.load(response)
    header = [
        f"# Generated by scripts/update-slack-emoji-names.py from emoji-datasource {version}.",
        "# Format: <emoji>\\t<slack name>[,<alias>...]; the first name is canonical.",
    ]
    OUTPUT.write_text("\n".join(header + build_lines(entries)) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
